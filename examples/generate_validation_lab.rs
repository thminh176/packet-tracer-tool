//! Original, synthetic two-router validation lab. No activity answers or device execution.
//! cargo run --example generate_validation_lab > audit-output/router-validation.txt
use pka_lab_inspector::{commands, model::Checkpoint};

fn main() {
    println!("! SYNTHETIC TEST LAB ONLY: connect two 2911 GigabitEthernet0/0 ports.");
    println!("! Review interface inventory first. Paste each device block separately.");
    println!("! Generated by the real checkpoint API; NOT execution-certified in Packet Tracer.");
    let mut checks = Vec::new();
    for (device, transit, lan, destination, next_hop) in [
        (
            "Lab-R1",
            "10.0.12.1",
            "192.0.2.1",
            "198.51.100.0",
            "10.0.12.2",
        ),
        (
            "Lab-R2",
            "10.0.12.2",
            "198.51.100.1",
            "192.0.2.0",
            "10.0.12.1",
        ),
    ] {
        for (interface, property, expected) in [
            ("", "Hostname", device.to_string()),
            (
                "GigabitEthernet0/0",
                "IPv4 Address",
                format!("{transit} 255.255.255.252"),
            ),
            ("GigabitEthernet0/0", "Interface Status", "enabled".into()),
            ("Loopback0", "IPv4 Address", format!("{lan} 255.255.255.0")),
            (
                "",
                "Static Route",
                format!("{destination} 255.255.255.0 {next_hop}"),
            ),
        ] {
            let c = Checkpoint {
                device: device.into(),
                device_type: "Router".into(),
                interface: interface.into(),
                property: property.into(),
                expected,
                evidence: vec!["assessment:device-model=2911".into()],
                ..Default::default()
            };
            let command = commands::generate(&c);
            assert!(
                command.supported && !command.gui,
                "{}: {}",
                c.property,
                command.explanation
            );
            checks.push(c);
        }
    }
    println!("{}", commands::device_script(&checks, None));
    println!("! After each block: show ip interface brief; show ip route static.");
    println!("! R1: ping 198.51.100.1 source 192.0.2.1 (if supported by simulator).");
    println!("! Save configuration only after reviewing actual show output and connectivity.");
}
